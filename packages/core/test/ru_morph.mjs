import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { fileURLToPath } from 'node:url';
import { openDatabase, breakdownWord } from '../dist/db/index.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DB_PATH =
  process.env.ZIDIANKAIFA_DB ?? path.resolve(__dirname, '..', '..', '..', 'data', 'db', 'dict.db');

// ★ 必须**只读**打开冻结词库：本判别集是纯读取断言（实测无 bookAdd/bookRemove/db.exec/.run）。
//   用 `openDatabase()` 会跑迁移 ⇒ **写冻结库**：每跑一次门禁就落一份 ~493 MB 的
//   `dict.db.bak-<ISO>` 快照 + WAL，造成无界磁盘增长并破坏 `data/**` 的冻结语义。
const db = new DatabaseSync(DB_PATH, { readOnly: true });
let pass = 0;
let fail = 0; // 回归护栏失败

function eq(label, got, want) {
  const isOk = JSON.stringify(got) === JSON.stringify(want);
  if (isOk) {
    pass++;
    console.log(`  ✓ ${label}`);
  } else {
    fail++;
    console.log(
      `  ✗ ${label}\n      实得 ${JSON.stringify(got)}\n      期望 ${JSON.stringify(want)}` +
        '\n      （回归！必须回退改动）',
    );
  }
}

function ok(label, cond, extra = '') {
  if (cond) {
    pass++;
    console.log(`  ✓ ${label}`);
  } else {
    fail++;
    console.log(`  ✗ ${label} ${extra}\n      （回归！必须回退改动）`);
  }
}

const bd = (w, lang = 'ru') => breakdownWord(db, w, lang).map((p) => p.morpheme);
const bdFull = (w) => breakdownWord(db, w, 'ru');
/** 位置显式判定：word 中是否存在 kind=kind 且位于规范位（prefix→词首 / suffix→词尾）的 morpheme */
const atCanonical = (w, m, kind) =>
  bdFull(w).some(
    (p) =>
      p.morpheme === m &&
      p.kind === kind &&
      (kind === 'prefix' ? p.start === 0 : p.end === w.length),
  );

/* ================= A. 正例 10 词（当前已绿 · 准确率护栏）================= */

console.log('--- A. 正例 10 词（应被正确拆解：真实词素 + 分段正确）---');
{
  // 理由：пере-（越过/重新）是俄语最典型的生产性前缀，пис-（写）是核心词根，
  // -ать 是动词不定式后缀。三段均真实且首尾相接，无空洞 —— 是「前缀+词根+不定式」的标尺。
  eq('переписать = пере- + пис- + -ать', bd('переписать'), ['пере-', 'пис-', '-ать']);

  // 理由：与前词共用词根但换前缀 за-（开始/在…之后），用来验证 DP 不依赖单一前缀。
  eq('записать = за- + пис- + -ать', bd('записать'), ['за-', 'пис-', '-ать']);

  // 理由：同族第三个前缀 на-（在…上/积累），三词并列可判别「只对某个前缀特判」的假实现。
  eq('написать = на- + пис- + -ать', bd('написать'), ['на-', 'пис-', '-ать']);

  // 理由：чит-（读）+ -тель（施动者）是 -тель 后缀的**语义正确**用法，
  // 必须与反例 ателье（-тель 误拆）成对存在 —— 只禁不立会把 -тель 整条规则误杀。
  eq('читатель = чит- + -тель', bd('читатель'), ['чит-', '-тель']);

  // 理由：-ик 指小后缀。домик = дом（房子）的指小形，语义与词根严格同族。
  eq('домик = дом- + -ик', bd('домик'), ['дом-', '-ик']);

  // 理由：与 домик 同后缀、换词根（стол 桌子），验证后缀规则对词根无偏。
  eq('столик = стол- + -ик', bd('столик'), ['стол-', '-ик']);

  // 理由：-ник（从事者）与 -ик（指小）是两个不同后缀，且 лес- 是短词根（3 字符）。
  // 用来判别「后缀剥离时误伤短词根」——正是 A2 提高后缀覆盖率时最容易踩的坑。
  eq('лесник = лес- + -ник', bd('лесник'), ['лес-', '-ник']);

  // 理由：-ный 是 A2 路径上最高频的后缀（「仅后缀」占可提升空间的 28.7%），
  // 必须有一条 -ный 的**正确**正例作为放宽后缀剥离时的护栏。
  eq('водный = вод- + -ный', bd('водный'), ['вод-', '-ный']);

  // 理由：希腊借词复合（теле- 远 + скоп- 观察镜）。与反例 стетоскоп 同尾，
  // 成对可判别「是否用 -скоп 语境而非 тоск- 子串」——стетоскоп 曾被误拆出 тоск-。
  eq('телескоп = теле- + скоп-', bd('телескоп'), ['теле-', 'скоп-']);

  // 理由：本土复合词（пар 蒸汽 + 连接元音 о + ход 走）。与 телескоп 分属不同构词路径，
  // 用于判别实现是否只对希腊/拉丁借词有效、对本土复合词失效。
  eq('пароход = паро- + ход-', bd('пароход'), ['паро-', 'ход-']);
}

/* ===== A2'. ★真前缀探针 удачный（裁决六 §五.1 批准写入 · 恒绿）===== */

console.log("--- A2'. ★真前缀探针 удачный（「选 >=1 而非无条件禁止 gap=1」的唯一点名实证）---");
{
  // 背景（裁决六 §五）：`удачный` 是「修法选 `>= 1` 而非无条件禁止 gap=1」的**唯一点名实证**。
  // 对照组「无条件禁止 gap=1」会**额外误杀** `удачный`（覆盖率再压到 237、误伤 7 词）。
  // 实测：`удачный` 改后仍为 {да-@1 + -ный@4}，gap='у' ∈ 库内单字符前缀 ⇒ 被 :851 放行。
  // 它同时是**真前缀组里唯一落在尺子 R 内的词**，故本文件必须长期持有它。
  eq('удачный = да- + -ный（gap у- 被放行，未被误杀）', bd('удачный'), ['да-', '-ный']);

  // 位置显式（与 ru_morph_d1fix.mjs §2 的放行组不变量同构）：
  // 首字符 у 是**被 gapExplain 解释掉的 gap**，不进入 parts ⇒ parts[0] 必起于位置 1。
  ok(
    'удачный 的 parts[0] 起于位置 1（у 是 gap，不进入 parts）',
    bdFull('удачный')[0]?.start === 1,
    `实得 ${JSON.stringify(bdFull('удачный').map((p) => `${p.morpheme}@${p.start}`))}`,
  );
  ok(
    "удачный **不得拆出处于词首位置的** у-（у 是 gapExplain 解释的 gap，非 parts 片段）",
    !atCanonical('удачный', 'у-', 'prefix'),
    `实得 ${JSON.stringify(bd('удачный'))}`,
  );

  // 同族三词对照：удаться 同机制放行；удача 因覆盖不足仍不可拆。
  // 三者并列可判别实现是否对 `удачный` 做了**单点特判**（那会同时把 удача 也拆开）。
  eq('удаться = да- + -ся（同族，同机制）', bd('удаться'), ['да-', '-ся']);
  eq('удача 不可拆（拆分覆盖不足，同族反面对照）', bd('удача'), []);
}

