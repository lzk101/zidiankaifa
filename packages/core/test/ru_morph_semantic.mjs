/**
 * T20 · 「真词根 vs 巧合词根」语义判别集（功能测试 agent 独立建立 · 2026-09-16）
 *
 * ⚠ 本文件**不接入 `pnpm test`**（`packages/core/package.json` 不在功能测试 agent 的可写范围）。
 *   v0.9.0 只做「防假拆解」，本文件是其**语义验收层**：现为红，修复后应全绿。
 *
 * ══════════════════════════════════════════════════════════════════════════════
 * 判别原理（一句话）
 * ══════════════════════════════════════════════════════════════════════════════
 * 引擎的假拆解**不是**「词素库里没有这个词素」的问题，而是
 *   **把真词根的一个子串当成了另一个同形词素**：
 *
 *   сучок  真词根 суч-（*sučiti / сук「节、枝」）→ 引擎让 уч-（*učiti「教、学」）在位置 1 命中
 *   вдавить 真词根 дав-（дави́ть「压」）        → 引擎让 да-（*dati「给」）在位置 1 命中
 *   ударить 真词根 дар-（*udariti ↔ драть）     → 引擎让 да-（*dati「给」）在位置 1 命中
 *   однако  单词素连词                          → 引擎让 дн-（*dьnь「日」）在位置 1 命中
 *
 * ⇒ 判据 = **词源上不同源**（真词素的原始形式 ≠ 命中词素的原始形式），
 *   而不是「长得像不像」。这与主管临时判据一致 —— 本文件把它**独立复核并固化**。
 *
 * ══════════════════════════════════════════════════════════════════════════════
 * 判据来源（每条断言都可复核；URL 见文件末尾 SOURCES）
 * ══════════════════════════════════════════════════════════════════════════════
 *  ① `{{морфо-ru}}` —— ru.wiktionary 的**权威词素切分模板**，逐词给出真词根/词缀边界。
 *     例：`сучок` → `суч|-ок|+∅`；`вдавить` → `в-|дав|-и|+ть`；`ударить` → `у-|дар|-и|+ть`。
 *  ② 库内 `word_etymology.chain[].parts` —— **产品自带数据**的第二成分（如 `[в-, дави́ть]`）。
 *  ③ 库内 `morphemes.origin` —— 命中词素的原始形式（如 `уч-` = `*učiti`）。
 *  ④ 真词根是否被收录（`morphemes` 查无）—— 解释「为什么引擎只能退而求其次」。
 *
 * ══════════════════════════════════════════════════════════════════════════════
 * 断言形式（主管硬约束：**必须带位置**）
 * ══════════════════════════════════════════════════════════════════════════════
 *  · 巧合：`不得出现 <词素> 处于位置 <start>`（不是笼统「不含 X」）
 *  · 真  ：`必须出现 <词素> 处于位置 <start>`（**反向对照**，防止修复时误杀真前缀）
 *  · 真词根跨度：`位置 [a,b)（真词根）不得整段成为空洞`
 *
 * ══════════════════════════════════════════════════════════════════════════════
 * 退出码约定（沿用 `ru_morph.mjs`）
 * ══════════════════════════════════════════════════════════════════════════════
 *   0 = 全绿（迭代目标达成） · 1 = **回归**（真词素/反向对照被误杀 ⇒ 必须回退）
 *   2 = 仅「巧合词根」目标项未达成（**预期红**，即 v0.9.0 待办）
 *
 * 运行（两种 cwd 都必须 exit 2）：
 *   node packages/core/test/ru_morph_semantic.mjs
 *   cd packages/core; node test/ru_morph_semantic.mjs
 */
