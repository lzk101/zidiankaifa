/* ---------- 位置显式取值工具 ---------- */

const partsOf = (w) => breakdownWord(db, w, 'ru');
/** 位置显式：**给定片段数组**中是否存在处于位置 start 的该词素（供合成片段自测复用） */
const atPosIn = (parts, m, start) => parts.some((p) => p.morpheme === m && p.start === start);
/** 位置显式：**给定片段数组**是否完全覆盖 [a,b) */
const spanCoveredIn = (parts, len, a, b) => {
  const cov = new Array(len).fill(false);
  for (const p of parts) for (let i = p.start; i < p.end && i < len; i++) cov[i] = true;
  for (let i = a; i < b; i++) if (!cov[i]) return false;
  return true;
};
/** 是否存在【处于位置 start 的】该词素片段 */
const atPos = (w, m, start) => atPosIn(partsOf(w), m, start);
/** 位置 [a,b) 是否被某片段**完全**覆盖 */
const spanCovered = (w, a, b) => spanCoveredIn(partsOf(w), w.length, a, b);
const fmtP = (w) => JSON.stringify(partsOf(w).map((p) => `${p.morpheme}@${p.start}-${p.end}`));

