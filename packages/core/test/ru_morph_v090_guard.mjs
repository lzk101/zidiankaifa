// ══════════════════════════════════════════════════════════════════════════════
// §7b [V090-GUARD] 全库扫描：V9-2 假词根残留 = 0，且词首空洞模式唯一
// ══════════════════════════════════════════════════════════════════════════════
console.log('\n--- §7b [V090-GUARD] 全库扫描（101,512 词，约 21 s）：V9-2 不变量 ---');
{
  // 为什么值得付 21 s：§2 只冻结了主管点名的 12 词，而 V9-2 的缺陷形态
  // （假词根在**位置 1** 命中，因词首 1 字符被跳过）是**模式**，不是 12 个词。
  // 本块把模式本身扫全库：
  //   ① 首片段 = уч-@1 的词数必须为 0（修前 = 11，*sučiti ≠ *učiti）
  //   ② 首片段 = дн-@1 的词数必须为 0（修前 = 1，однако 为单词素）
  //   ③ 全库**唯一**首片段 start===1 的模式只允许是 да-@1，且恰 63 词
  //      —— да- 族属「已登记不处理」（真假同形，见 §3/§9），是**已知**边界；
  //         若出现 да-@1 以外的模式，说明又冒出了新的词首假词根 ⇒ 回归。
  const t0 = Date.now();
  const rows = db.prepare("SELECT word FROM words_i18n WHERE lang = 'ru'").all();
  const byFirst = new Map();
  let decomposable = 0;
  for (const { word } of rows) {
    const parts = breakdownWord(db, word, 'ru');
    if (!parts.length) continue;
    decomposable++;
    const key = `${parts[0].morpheme}@${parts[0].start}`;
    if (!byFirst.has(key)) byFirst.set(key, []);
    byFirst.get(key).push(word);
  }
  const elapsed = Date.now() - t0;

  const uch = byFirst.get('уч-@1') ?? [];
  const dn = byFirst.get('дн-@1') ?? [];
  const da = byFirst.get('да-@1') ?? [];
  const pos1Keys = [...byFirst.keys()].filter((k) => k.endsWith('@1')).sort();

  eq('§7b 全库 ru 词条数 = 101,512（冻结值）', rows.length, 101512);
  eq('§7b 全库可拆词数 = 33,495（v0.9.0 冻结值）', decomposable, 33495);
  eq('§7b ★ 首片段 уч-@1 的词数 = 0（V9-2 全库无残留）', uch.length, 0);
  eq('§7b ★ 首片段 дн-@1 的词数 = 0（V9-2 全库无残留）', dn.length, 0);
  eq('§7b ★ 首片段 start===1 的模式集合 = [да-@1]（唯一已知边界）', pos1Keys, ['да-@1']);
  eq('§7b ★ 首片段 да-@1 的词数 = 63（已登记不处理，冻结值）', da.length, 63);
  ok('§7b 扫描耗时在预算内（< 60 s）', elapsed < 60000, `${elapsed} ms`);
  console.log(`  · 扫描口径：全库 101,512 条 ru 词条逐词调 breakdownWord（dist），耗时 ${elapsed} ms`);
  console.log(`  · да-@1 63 词样例：${da.slice(0, 6).join(' ')} …`);
}

