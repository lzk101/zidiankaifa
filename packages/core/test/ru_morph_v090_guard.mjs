const bd = (w, lang = 'ru') => partsOf(w, lang).map((p) => p.morpheme);

/** 逐字冻结比较（回归锁主体） */
function eq(label, got, want) {
  const ok = JSON.stringify(got) === JSON.stringify(want);
  if (ok) {
    pass++;
    console.log(`  ○ ${label}`);
  } else {
    fail++;
    console.log(
      `  ✗ ${label}\n      实得 ${JSON.stringify(got)}\n      期望 ${JSON.stringify(want)}` +
        `\n      （v0.9.0 发布态冻结值被打破 = 回归，须回退或由主管裁决）`,
    );
  }
}

/** 位置显式断言：必须存在 {morpheme, start} 恰好匹配的片段（AGENTS.md 铁律：断言必须带位置） */
function at(label, w, morpheme, start) {
  const hit = partsOf(w).some((p) => p.morpheme === morpheme && p.start === start);
  if (hit) {
    pass++;
    console.log(`  ○ ${label}`);
  } else {
    fail++;
    console.log(
      `  ✗ ${label}\n      实得 ${JSON.stringify(bd(w))}\n      期望含 ${morpheme}@${start}`,
    );
  }
}

/** 位置显式否证：不得存在 {morpheme, start}（用于「假词根不得复活」） */
function notAt(label, w, morpheme, start) {
  const hit = partsOf(w).some((p) => p.morpheme === morpheme && p.start === start);
  if (!hit) {
    pass++;
    console.log(`  ○ ${label}`);
  } else {
    fail++;
    console.log(
      `  ✗ ${label}\n      实得 ${JSON.stringify(bd(w))}\n      不得出现 ${morpheme}@${start}（假拆解复活 = 回归）`,
    );
  }
}

/** 通用布尔断言 */
function ok(label, cond, detail = '') {
  if (cond) {
    pass++;
    console.log(`  ○ ${label}`);
  } else {
    fail++;
    console.log(`  ✗ ${label}${detail ? `\n      ${detail}` : ''}`);
  }
}

